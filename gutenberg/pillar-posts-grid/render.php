<?php
/**
 * Render the Pillar Posts Grid ACF block.
 *
 * @package News
 */

$is_preview = isset( $is_preview ) && $is_preview;

if ( ! function_exists( 'get_field' ) ) {
	return;
}

$section_title = trim( (string) get_field( 'section_title' ) );
$selected_posts = get_field( 'selected_posts' );
$show_image_value = get_field( 'show_image' );
$show_excerpt_value = get_field( 'show_excerpt' );
$show_image = null === $show_image_value ? true : (bool) $show_image_value;
$show_excerpt = null === $show_excerpt_value ? true : (bool) $show_excerpt_value;
$guide_items = array();

foreach ( (array) $selected_posts as $selected_post ) {
	$selected_post_id = $selected_post instanceof WP_Post ? $selected_post->ID : absint( $selected_post );
	$post_type = get_post_type( $selected_post_id );

	if ( ! $selected_post_id || ! in_array( $post_type, array( 'post', 'page' ), true ) ) {
		continue;
	}

	$thumbnail = null;

	if ( $show_image && has_post_thumbnail( $selected_post_id ) ) {
		$thumbnail_id = get_post_thumbnail_id( $selected_post_id );
		$thumbnail = function_exists( 'get_image_data' )
			? get_image_data( $thumbnail_id, 'archive_post' )
			: null;
	}

	$guide_items[] = array(
		'ID'        => $selected_post_id,
		'permalink' => get_permalink( $selected_post_id ),
		'title'     => get_the_title( $selected_post_id ),
		'excerpt'   => $show_excerpt ? get_the_excerpt( $selected_post_id ) : '',
		'thumbnail' => $thumbnail,
	);

	if ( 12 === count( $guide_items ) ) {
		break;
	}
}

if ( empty( $guide_items ) ) {
	if ( ! $is_preview ) {
		return;
	}

	$empty_attributes = function_exists( 'get_block_wrapper_attributes' )
		? get_block_wrapper_attributes(
			array(
				'class' => 'p-pillar__cluster c-pillar-posts-grid',
			)
		)
		: 'class="p-pillar__cluster c-pillar-posts-grid"';
	?>
	<div <?php echo $empty_attributes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress. ?>>
		<p class="c-pillar-posts-grid__notice">
			<?php esc_html_e( 'Select posts or pages in the block settings to display the grid.', 'news' ); ?>
		</p>
	</div>
	<?php
	return;
}

$block_instance = ! empty( $block['id'] ) ? sanitize_html_class( $block['id'] ) : wp_unique_id( 'pillar-posts-grid-' );
$heading_id = $block_instance . '-heading';
$extra_attributes = array(
	'class' => 'p-pillar__cluster c-pillar-posts-grid',
);

if ( '' !== $section_title ) {
	$extra_attributes['aria-labelledby'] = $heading_id;
}

$wrapper_attributes = function_exists( 'get_block_wrapper_attributes' )
	? get_block_wrapper_attributes( $extra_attributes )
	: 'class="p-pillar__cluster c-pillar-posts-grid"';
?>
<section <?php echo $wrapper_attributes; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress. ?>>
	<?php if ( '' !== $section_title ) : ?>
		<h2 id="<?php echo esc_attr( $heading_id ); ?>" class="u-h2"><?php echo esc_html( $section_title ); ?></h2>
	<?php endif; ?>

	<div class="p-pillar__grid">
		<?php
		foreach ( $guide_items as $guide_item ) {
			Timber\Timber::render(
				'partial/guide-card.twig',
				array(
					'guide_item'   => $guide_item,
					'heading_level' => 3,
				)
			);
		}
		?>
	</div>
</section>
